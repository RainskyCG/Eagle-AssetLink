      const manifest=JSON.parse(fs.readFileSync(path.join(root,'shortcuts',action,'manifest.json'),'utf8'));
      assert(!manifest.main.runAfterInstall);assert(!manifest.shortcut);
      await open('shortcuts/'+action+'/index.html');
      await page.waitForSelector(action==='locate'?'.command-shell [data-select-group]':'.command-shell .notice');
